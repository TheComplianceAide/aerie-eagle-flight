"""Add measured Hamnøy fetch to the alpha plane of the original atlas shore image.

The existing lossy VP8 principal image is copied byte-for-byte. Geometry and
terrain come from the installed Kartverket local survey and the fjord DEM.
"""
import argparse
import base64
import io
import json
import struct
from pathlib import Path
import numpy as np
from PIL import Image
from scipy.ndimage import gaussian_filter, map_coordinates


def smooth(lo, hi, x):
    v = np.clip((x-lo)/(hi-lo), 0, 1)
    return v*v*(3-2*v)


def chunks(data):
    cursor = 12
    while cursor + 8 <= len(data):
        tag, size = struct.unpack_from("<4sI", data, cursor)
        yield tag, data[cursor+8:cursor+8+size]
        cursor += 8 + size + (size & 1)


def pack(tag, data):
    return tag+struct.pack("<I", len(data))+data+b"\0"*(len(data)&1)


def harbor_alpha(game, width, height):
    atlas = json.loads((game/"atlas-lofoten-survey.js").read_text().split("]=")[-1].rstrip(";\n"))
    full = np.frombuffer(base64.b64decode(atlas["terrain"]), "<i2")
    full = full.reshape(round(np.sqrt(full.size)), -1).astype(float)*.25
    detail = (game/"landform-hamnoy.bin").read_bytes()
    _, _, step, left, top, right, bottom, nx, nz, datum, unit, _ = struct.unpack_from("<4sHH4iHHffI", detail)
    harbor = np.frombuffer(detail, "<i2", offset=40, count=nx*nz).reshape(nz, nx)*unit+datum
    half = atlas["half"]
    def ground(x, z):
        coarse = map_coordinates(full, [(z+half)/(2*half)*(len(full)-1),(x+half)/(2*half)*(len(full)-1)],order=1,mode="nearest")
        local = map_coordinates(harbor, [(z-top)/step,(x-left)/step],order=1,mode="nearest")
        return np.where((x>left)&(x<right)&(z>top)&(z<bottom),local,coarse)
    # Incoming wave components in water-surface.js propagate east-southeast.
    # Cast back from each inlet sample over an angular spread around that bearing.
    z, x = np.mgrid[0:height, 0:width]
    x, z = ((x+.5)/width*2-1)*half, ((z+.5)/height*2-1)*half
    frame = np.minimum.reduce([x-left, right-x, z-top, bottom-z])
    inside = frame > 0
    p, q = x[inside], z[inside]
    energy = np.zeros_like(p)
    for angle in np.linspace(-54, 54, 13):
        theta = np.arctan2(-.475,-.88) + np.deg2rad(angle)
        first = np.full(len(p), 2400.)
        for distance in np.geomspace(4, 2400, 55):
            onland = ground(p+np.cos(theta)*distance, q+np.sin(theta)*distance) > .24
            first = np.where(onland, np.minimum(first, distance), first)
        # Saturating wave energy from unobstructed water upwind. Short harbor
        # rays retain capillary chop but cannot build a train of breaking swell.
        energy += smooth(140, 1700, first)/13
    coverage = np.ones((height,width), dtype=float)
    coverage[inside] = 1 + (energy-1)*smooth(0,80,frame[inside])
    coverage = gaussian_filter(coverage,.85)
    return np.rint(128+127*np.clip(coverage,0,1)).astype("u1")


def bake(game, output):
    source = (game/"atlas-lofoten-shore.webp").read_bytes()
    image = Image.open(io.BytesIO(source))
    width, height = image.size
    alpha = harbor_alpha(game, width, height)
    # WebP ALPH prediction/compression is generated by libwebp. Keep original
    # VP8 color independently so the unchanged fjord has identical decoded data.
    carrier = Image.new("RGBA", image.size, (143,143,143,255))
    carrier.putalpha(Image.fromarray(alpha)); buffer = io.BytesIO(); carrier.save(buffer, format="WEBP", quality=80)
    a = next(data for tag, data in chunks(buffer.getvalue()) if tag==b"ALPH")
    color = next(data for tag, data in chunks(source) if tag==b"VP8 ")
    ext = b"\x10\0\0\0"+(width-1).to_bytes(3,"little")+(height-1).to_bytes(3,"little")
    result = b"WEBP"+pack(b"VP8X",ext)+pack(b"ALPH",a)+pack(b"VP8 ",color)
    output.write_bytes(b"RIFF"+struct.pack("<I",len(result))+result)


if __name__ == "__main__":
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--game",type=Path,required=True); parser.add_argument("--output",type=Path,required=True)
    args=parser.parse_args();bake(args.game,args.output)
